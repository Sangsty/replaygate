package main

import (
	"fmt"
	"io"
	"strings"
	"time"
)

func pct(k, n int) string {
	if n == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%.0f%%", 100*float64(k)/float64(n))
}

func ci(lo, hi float64) string { return fmt.Sprintf("%.1f%%–%.1f%%", 100*lo, 100*hi) }

func secs(d time.Duration) string { return fmt.Sprintf("%.1f s", d.Seconds()) }

// verdict summarises the seeded-bug results in one sentence for the top of the
// report. Every number in it is computed from the rows below it.
func (r Results) summary() (caught, total, named int) {
	for _, b := range r.Bugs {
		total++
		if b.Detected == b.Runs && b.Runs > 0 {
			caught++
		}
		if b.Located == b.Runs && b.Runs > 0 {
			named++
		}
	}
	return
}

// Markdown renders the results as docs/evaluation.md.
func (r Results) Markdown(w io.Writer) {
	p := func(format string, a ...any) { fmt.Fprintf(w, format+"\n", a...) }
	e := r.Env

	p("# Evaluation")
	p("")
	p("Generated by `make eval` on %s. This file is machine-written: run the command again to refresh it, do not edit it by hand.", e.When.Format("2006-01-02"))
	p("")
	p("## Setup")
	p("")
	p("| | |")
	p("|---|---|")
	p("| Machine | %s/%s, %d CPUs |", e.OS, e.Arch, e.CPUs)
	p("| Go | %s |", e.Go)
	p("| Database | %s |", e.Postgres)
	p("| Replay concurrency | %d requests in flight per worker |", e.Concurrency)
	p("| Recorded corpus | 210 requests: 60 users, 60 orders, 60 products, 30 searches |")
	p("")
	p("The API, the diff worker, the replay workers, the gate and both services under test all run in one process on one machine, against a real Postgres. The services are the synthetic shop in `internal/evalapp`: every response carries fields that change on every call (`ts`, `request_id`, `etag`, `updated_at`, `took_ms`), and the candidate build has one change switched on per run.")
	p("")

	caught, total, named := r.summary()
	p("## 1. Seeded bugs")
	p("")
	p("Each bug is a different class of mistake and touches only some of the requests. A bug counts as *caught* when the check fails, and as *named* when the report also lists the expected change (right endpoint, right kind, right JSON path). Runs use noise learning with the default settings (`fail_on: breaking`).")
	p("")
	p("**%d of %d bugs caught in every run; %d of %d named correctly in every run.**", caught, total, named, total)
	p("")
	p("| Bug | What changed | Caught | Named in the report |")
	p("|---|---|---|---|")
	for _, b := range r.Bugs {
		p("| `%s` | %s | %d/%d | %d/%d |", b.Spec.Name, b.Spec.Description, b.Detected, b.Runs, b.Located, b.Runs)
	}
	p("")
	p("Controls: changes that are safe and should **not** fail the check.")
	p("")
	p("| Change | What changed | Check passed | Findings reported |")
	p("|---|---|---|---|")
	for _, b := range r.Benign {
		p("| `%s` | %s | %d/%d | %d |", b.Spec.Name, b.Spec.Description, b.Passed, b.Runs, b.Findings)
	}
	p("")

	p("## 2. False alarms")
	p("")
	p("The same build is replayed as baseline and as candidate, so any failed check is a false alarm. %d checks per row; the interval is a 95%% Wilson score interval.", r.Config.FPRuns)
	p("")
	p("| Setting | False alarms | Rate (95%% interval) | Breaking findings per check | Checks with a latency finding |")
	p("|---|---|---|---|---|")
	for _, f := range r.FP {
		p("| %s | %d/%d | %s (%s) | %.2f | %d/%d |", f.Label, f.Failed, f.Runs, pct(f.Failed, f.Runs), ci(f.CILo, f.CIHi), f.MeanBreaking, f.LatencyRuns, f.Runs)
	}
	p("")
	for _, f := range r.FP {
		if f.Errored > 0 {
			p("> %d check(s) in %q ended without a verdict and are not counted as alarms.", f.Errored, f.Label)
			p("")
		}
	}

	p("## 3. Throughput")
	p("")
	p("A clean check of N recorded requests replays each one three times (baseline twice for noise learning, then the candidate), stores every response, and diffs them. Timings include creating the run and storing all responses.")
	p("")
	p("| Recorded requests | Requests replayed | Total | Replay | Diff | Replays per second | Latency findings | Verdict |")
	p("|---|---|---|---|---|---|---|---|")
	for _, b := range r.Bench {
		p("| %d | %d | %s | %s | %s | %.0f | %d | %s |", b.Requests, b.Replays, secs(b.Total), secs(b.Replay), secs(b.Diff), b.PerSecond, b.Latency, strings.ToUpper(b.Verdict))
	}
	p("")

	p("## Limits of these numbers")
	p("")
	p("- The services are synthetic and the ten bugs were chosen by the author. The catch rate says the gate finds these classes of change in this setup; it is not a recall figure for real services.")
	p("- Noise is of two kinds only: values that change on every call, and one field that flips rarely. Noise that depends on request order, load or time of day is not modelled.")
	p("- Everything shares one machine, and the services answer from memory over localhost, so network latency and slow downstream calls are not included. Real throughput is bounded by how fast the services under test respond.")
	p("- The diff worker polls every %s here; the API's production default is 1 s, which adds up to a second to every check.", diffPoll)
	p("- Latency findings compare a single sample per request, so they are noisy; they are reported but never fail a check by default.")
	p("")
	p("Reproduce: `make eval` (needs the Postgres from `make up`).")
}
